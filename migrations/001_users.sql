-- Baseline reference for a new database; do not replay on the configured Neon DB.
-- The existing Neon table is retained; registration/RBAC changes are recorded in 002.
BEGIN;

CREATE TABLE IF NOT EXISTS public.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255),
    is_active BOOLEAN DEFAULT TRUE,
    fcm_token VARCHAR(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Existing duplicate identities cause this transaction to fail without deleting data.
CREATE UNIQUE INDEX IF NOT EXISTS users_email_normalized_uidx
    ON public.users (lower(btrim(email)));
CREATE UNIQUE INDEX IF NOT EXISTS users_username_normalized_uidx
    ON public.users (lower(btrim(username)));

COMMIT;
